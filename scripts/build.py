"""Build the app from src/ into two files.

index.html             the GitHub Pages site (full page with Home Screen icon and app name)
dist/artifact.html     the same app as a claude.ai artifact body (the artifact host adds the page wrapper)
Run: python3 scripts/build.py
"""
import os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
read = lambda p: open(os.path.join(root, p), encoding="utf-8").read()
body = read("src/shell.html") + '\n<script id="core">\n' + read("src/core.js") + '</script>\n<script id="ui">\n' + read("src/ui.js") + "</script>\n"
head = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="theme-color" content="#1D5B48">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="OMGym">
<meta name="apple-mobile-web-app-status-bar-style" content="default">
<meta name="description" content="45-minute workouts and budget meal plans with local food prices.">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<link rel="icon" type="image/png" sizes="32x32" href="icons/favicon-32.png">
<link rel="manifest" href="manifest.webmanifest">
<style>:root{color-scheme:light;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}html{-webkit-text-size-adjust:100%}body{margin:0}img{max-width:100%}[hidden]{display:none!important}</style>
</head>
<body>
"""
open(os.path.join(root, "index.html"), "w", encoding="utf-8").write(head + body + "</body>\n</html>\n")
os.makedirs(os.path.join(root, "dist"), exist_ok=True)
open(os.path.join(root, "dist/artifact.html"), "w", encoding="utf-8").write(body)
# offline support for the Home Screen app (GitHub Pages only; the artifact host has its own caching)
import hashlib
ver = hashlib.sha1(body.encode("utf-8")).hexdigest()[:10]
sw = """// OMGym offline cache. Generated by scripts/build.py; do not edit by hand.
const CACHE = 'omgym-%s';
const FILES = ['./', 'index.html', 'manifest.webmanifest', 'icons/apple-touch-icon.png', 'icons/icon-192.png', 'icons/icon-512.png', 'icons/favicon-32.png'];
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('omgym-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const u = new URL(e.request.url);
  if (e.request.method !== 'GET' || u.origin !== location.origin) return;
  // network first so updates arrive; fall back to the cached copy when offline
  e.respondWith(fetch(e.request).then(r => { const c = r.clone(); caches.open(CACHE).then(k => k.put(e.request, c)); return r; }).catch(() => caches.match(e.request).then(m => m || caches.match('index.html'))));
});
""" % ver
open(os.path.join(root, "sw.js"), "w", encoding="utf-8").write(sw)
print("built index.html, sw.js and dist/artifact.html")
